"""Writes RESULTS_SUMMARY.md from the files produced by clean_and_load.py and train_model.py,
so the document always matches your own run.   Usage: python3 write_results_summary.py"""
import json
import pandas as pd
from config import METRICS_PATH, PROCESSED_DATA_PATH, RISK_PREDICTIONS_PATH

m = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
d = pd.read_csv(PROCESSED_DATA_PATH)
sel = m["selected_model"]
rate = lambda col, val: d.loc[d[col] == val, "AttritionFlag"].mean() * 100
lines = ["# Results Summary", "", "Generated by `write_results_summary.py` from this project's own outputs.", "",
         "## Data", "", f"- {len(d):,} employees, {int(d.AttritionFlag.sum())} who left ({d.AttritionFlag.mean():.2%} attrition rate).",
         "- No duplicate rows or missing values. `EmployeeCount`, `Over18` and `StandardHours` are constant and not used for modelling.",
         "- Outliers (IQR rule) are clipped inside the model pipeline using training data only.", "",
         "## Model evaluation", "",
         f"Stratified 80/20 split ({m['training_set_size']} train / {m['test_set_size']} test). Selection: {m['selection_metric']}.", "",
         "| Model | CV ROC-AUC | Accuracy | Precision | Recall | F1 | Test ROC-AUC | Train seconds |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
for name, v in m["models"].items():
    lines.append(f"| {name}{' (selected)' if name == sel else ''} | {v['cv_roc_auc_mean']:.3f} | {v['accuracy']:.1%} | {v['precision']:.1%} | {v['recall']:.1%} | {v['f1_score']:.1%} | {v['roc_auc']:.3f} | {v['train_seconds']} |")
cm = m["models"][sel]["confusion_matrix"]
lines += ["", f"Confusion matrix of the selected model (rows = actual stay/leave, columns = predicted): `{cm}`.", "",
          f"Accuracy alone is misleading here: always predicting 'stay' would score {1 - d.AttritionFlag.mean():.1%}. "
          "The model is judged mainly by ROC-AUC and by recall of employees who actually left.", "",
          "## Observed patterns (descriptive, not causal)", "",
          f"- Overtime: {rate('OverTime', 'Yes'):.1f}% attrition vs {rate('OverTime', 'No'):.1f}% without overtime.",
          f"- Sales has {rate('Department', 'Sales'):.1f}% attrition vs {rate('Department', 'Research & Development'):.1f}% in Research & Development.",
          f"- First-year employees: {rate('TenureBand', '0-1 years'):.1f}% vs {rate('TenureBand', '11+ years'):.1f}% for 11+ years.",
          f"- Sales Representative is the highest-attrition role at {rate('JobRole', 'Sales Representative'):.1f}%.", ""]
if RISK_PREDICTIONS_PATH.exists():
    t = m.get("risk_tier_summary", {})
    lines += ["## Review queue", "", "| Risk tier | Employees | Observed attrition |", "| --- | ---: | ---: |"]
    for tier in ["High", "Medium", "Low"]:
        if tier in t:
            lines.append(f"| {tier} | {t[tier]['employees']} | {t[tier]['observed_attrition_rate']:.1%} |")
    lines += ["", m["risk_scores_note"], ""]
lines += ["Scores support a human retention conversation. They must not drive automatic employment decisions."]
open("RESULTS_SUMMARY.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("Wrote RESULTS_SUMMARY.md")
